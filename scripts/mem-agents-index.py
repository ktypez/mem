#!/usr/bin/env python3
"""Refresh the shared mem index inside ~/AGENTS.md.

The Hermes plugin injects the mem index live; every other agent runtime on this
host (opencode, pi, pi-bolt, ...) only reads instruction files. This script keeps
one managed block in ~/AGENTS.md so those runtimes also start a session knowing
what the store contains, without per-runtime hook support.

Managed block:

    <!-- mem-index:start -->
    ...generated, do not edit...
    <!-- mem-index:end -->

The block is rewritten in place (atomic replace). A failed fetch leaves the file
untouched so a down service can never blank the instructions.

Usage:
    mem-agents-index.py [--limit N] [--file PATH] [--print] [--check]
"""
from __future__ import annotations

import argparse
import os
import sys
import tempfile
import urllib.error
import urllib.request

BASE = os.environ.get("MEM_SERVICE_URL", "http://127.0.0.1:3200")
START = "<!-- mem-index:start -->"
END = "<!-- mem-index:end -->"
TOKEN_ENV = "MEM_API_TOKEN"
TOKEN_FILES = ("~/.hermes/.env", "/etc/mem/mem.env")
HEADING = "## What the memory store already knows (auto-generated)"
NOTE = ("_Generated by `mem-agents-index.py` from `/v1/memory/brief?format=text`; "
        "do not edit by hand. Open a page with `GET /v1/wiki/pages/<slug>?format=text` "
        "or the mem MCP tools before answering questions about this host._")


def service_token() -> str:
    token = os.environ.get(TOKEN_ENV, "").strip()
    if token:
        return token
    for path in TOKEN_FILES:
        try:
            with open(os.path.expanduser(path), encoding="utf-8", errors="replace") as fh:
                for line in fh:
                    key, _, value = line.partition("=")
                    if key.strip() in (TOKEN_ENV, "HERMES_MEMORY_SERVICE_TOKEN", "MEM_API_TOKEN"):
                        value = value.strip().strip("'\"")
                        if value:
                            return value
        except OSError:
            continue
    return ""


def fetch_index(limit: int) -> str:
    req = urllib.request.Request(
        f"{BASE}/v1/memory/brief?format=text&limit={limit}",
        headers={"Accept": "text/plain"},
    )
    token = service_token()
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    req.add_header("X-Mem-Source", "mem-agents-index")
    with urllib.request.urlopen(req, timeout=15) as resp:
        return resp.read().decode("utf-8", "replace").strip()


def render(index: str) -> str:
    return f"{START}\n{HEADING}\n\n{NOTE}\n\n```\n{index}\n```\n{END}"


def splice(text: str, block: str) -> str:
    start = text.find(START)
    end = text.find(END)
    if start != -1 and end != -1 and end > start:
        return text[:start] + block + text[end + len(END):]
    separator = "" if text.endswith("\n\n") else ("\n" if text.endswith("\n") else "\n\n")
    return text + separator + block + "\n"


def write_atomic(path: str, content: str) -> None:
    directory = os.path.dirname(path) or "."
    mode = os.stat(path).st_mode & 0o777 if os.path.exists(path) else 0o644
    fd, tmp = tempfile.mkstemp(dir=directory, prefix=".agents-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(content)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def main() -> int:
    parser = argparse.ArgumentParser(description="Refresh the shared mem index inside an instruction file.")
    parser.add_argument("--limit", type=int, default=10, help="pages in the index (default 10)")
    parser.add_argument("--file", default="~/AGENTS.md", help="instruction file to maintain")
    parser.add_argument("--print", action="store_true", dest="print_only",
                        help="print the index instead of writing")
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the file's block is out of date")
    args = parser.parse_args()

    try:
        index = fetch_index(args.limit)
    except (urllib.error.URLError, OSError, ValueError) as exc:
        print(f"mem-agents-index: fetch failed: {exc}", file=sys.stderr)
        return 1
    if not index:
        print("mem-agents-index: empty index, file untouched", file=sys.stderr)
        return 1
    if args.print_only:
        print(index)
        return 0

    path = os.path.expanduser(args.file)
    try:
        with open(path, encoding="utf-8") as fh:
            current = fh.read()
    except FileNotFoundError:
        current = ""

    updated = splice(current, render(index))
    if updated == current:
        return 0
    if args.check:
        print(f"{path}: index block is stale", file=sys.stderr)
        return 1
    write_atomic(path, updated)
    print(f"{path}: index refreshed ({len(index.splitlines()) - 1} page lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
